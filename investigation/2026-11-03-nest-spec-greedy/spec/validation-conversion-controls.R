Sys.setenv(TESTTHAT_PARALLEL = "false")
pkgload::load_all(Sys.getenv("MARGINPLYR_HUNT_SOURCE", unset = "."), quiet = TRUE)
capture <- function(expr) tryCatch(expr, error = identity)
cat("hms conversion method:\n")
print(getS3method("as.character", "hms", envir = asNamespace("hms")))
x <- tibble::tibble(g = hms::hms(numeric()), row_id = integer())
cat("hms ordinary conversion answer:\n")
str(as.character(x$g))
print(dplyr::mutate(x, g = as.character(g)))
cat("empty hms direct nesting and single-set Margin nesting:\n")
print(tidyr::nest(x, .by = g))
print(nest_with_margins(x, .grouping = grouping_set(g)))
cat("empty hms typed-missing rollup:\n")
print(nest_by_with_margins(x, .grouping = rollup(g), .margin_label = NULL))
cat("hms class removed before package entry:\n")
y <- x
y$g <- as.character(as.character(y$g))
print(nest_with_margins(y, .grouping = rollup(g)))
stopifnot(is.character(nest_with_margins(y, .grouping = rollup(g))$g))

cat("rvar ordinary conversion answer:\n")
r <- tibble::tibble(g = posterior::rvar(matrix(1, nrow = 4L, ncol = 1L)), row_id = 1L)
value <- as.character(r$g)
str(value)
print(capture(dplyr::if_else(value == "Total", 1L, 0L, missing = 0L)))
stopifnot(is.character(value), identical(as.vector(value), "1 ± 0"))
for (verb in c("nest_with_margins", "nest_by_with_margins")) {
  actual <- capture(get(verb)(r, .grouping = grouping_set(g)))
  unchecked <- get(verb)(r, .grouping = grouping_set(g), .check_margin_label = FALSE)
  typed <- get(verb)(r, .grouping = grouping_set(g), .margin_label = NULL)
  native <- tidyr::nest(r, .by = g)
  absent <- sum(as.vector(value) == "Total")
  present <- sum(as.vector(value) == value[[1L]])
  print(list(verb = verb, actual = if (inherits(actual, "error")) conditionMessage(actual) else actual,
             unchecked = unchecked, typed = typed, native = native, absent = absent, present = present))
  stopifnot(inherits(actual, "error"), nrow(unchecked) == 1L, nrow(typed) == 1L,
            identical(unchecked$data[[1L]]$row_id, 1L), absent == 0L, present == 1L)
}
print(sessionInfo())
