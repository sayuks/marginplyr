Sys.setenv(TESTTHAT_PARALLEL = "false")
pkgload::load_all(Sys.getenv("MARGINPLYR_HUNT_SOURCE", "."), quiet = TRUE)
library(dplyr)
root <- "investigation/2026-11-03-expand-grouping-greedy/lazy"
ll <- logLik(lm(c(1, 3, 2, 5) ~ c(1, 2, 3, 4)))
source <- tibble(g = ll, rid = 1L)
input <- dtplyr::lazy_dt(data.table::as.data.table(source), immutable = TRUE)
plain <- collect(input)
missing <- vctrs::vec_init(plain$g, 1L)
control <- union_all(input, mutate(input, g = vctrs::vec_rep(!!missing, length(g)))) |> collect()
stopifnot(inherits(control$g, "logLik"), identical(control$rid, c(1L, 1L)), is.na(control$g[[2L]]))
actual <- tryCatch(expand_with_margins(input, .grouping = rollup(g), .margin_label = NULL) |> collect(), error = identity)
cat("Control classes:", paste(class(control$g), collapse = "/"), "; rows:", nrow(control), "\n")
print(control)
cat("Expansion:\n")
print(actual)
proxy <- getFromNamespace("dtplyr_selection_proxy", "marginplyr")(input)
cat("Zero-row proxy class:", class(proxy$g), "\n")
cat("NA slice class:", class(proxy$g[NA_integer_]), "\n")
cat("vec_init class:", class(vctrs::vec_init(proxy$g, 1L)), "\n")
stopifnot(identical(source, plain))
if ("--assert" %in% commandArgs(trailingOnly = TRUE)) {
 stopifnot(!inherits(actual, "error"))
 stopifnot(isTRUE(all.equal(actual, control)))
}
