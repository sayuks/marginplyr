Sys.setenv(TESTTHAT_PARALLEL = "false")
pkgload::load_all(Sys.getenv("MARGINPLYR_HUNT_SOURCE", "."), quiet = TRUE)
suppressPackageStartupMessages(library(dplyr))
local({
  con <- DBI::dbConnect(RSQLite::SQLite())
  on.exit(DBI::dbDisconnect(con))
  src <- copy_to(con, tibble(g = "a", `TRUE` = 7L), "src", temporary = TRUE)
  opts <- dbplyr::sql_options(cte = TRUE)
  control <- collect(filter(src, TRUE), sql_options = opts)
  stopifnot(identical(names(control), c("g", "TRUE")), identical(control[["TRUE"]], 7L))
  x <- expand_with_margins(src, .grouping = rollup(g))
  direct <- collect(x)
  stopifnot(identical(names(direct), c("g", "TRUE")), identical(direct[["TRUE"]], c(7L, 7L)))
  sql <- dbplyr::sql_render(x, sql_options = opts)
  raw <- DBI::dbGetQuery(con, sql)
  cat("Ordinary filtered-source CTE control succeeded.\n")
  cat("Default expansion collection succeeded.\n")
  cat("CTE raw schema:", names(raw), "\n")
  print(raw)
  result <- tryCatch(collect(x, sql_options = opts), error = identity)
  if (inherits(result, "error")) cat("CTE collect error:", conditionMessage(result), "\n")
  if ("--assert" %in% commandArgs(trailingOnly = TRUE)) {
    stopifnot(!inherits(result, "error"), identical(names(result), names(direct)))
  }
})
