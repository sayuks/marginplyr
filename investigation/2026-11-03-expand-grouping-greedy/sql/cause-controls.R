Sys.setenv(TESTTHAT_PARALLEL = "false")
pkgload::load_all(Sys.getenv("MARGINPLYR_HUNT_SOURCE", "."), quiet = TRUE)
suppressPackageStartupMessages(library(dplyr))
local({
  con <- DBI::dbConnect(RSQLite::SQLite())
  on.exit(DBI::dbDisconnect(con))
  src <- copy_to(con, tibble(g = c("b", "a", NA_character_), rid = 1:3, `TRUE` = c(7L, 11L, 19L)), "src")
  x <- expand_with_margins(src, .grouping = rollup(g), .sort = "last", .id = "sid")
  mat <- compute(x, name = "control")
  for (shape in list(identity, function(y) semi_join(y, y, by = "g"), function(y) anti_join(y, y, by = "g"))) {
    cat("\nExpanded result:\n")
    print(collect(shape(x)))
    cat("Materialized control:\n")
    print(collect(shape(mat)))
  }
  cat("\nRaw direct physical columns:\n")
  print(names(DBI::dbGetQuery(con, dbplyr::sql_render(x))))
  cat("\nCollapsed physical columns:\n")
  print(names(collect(collapse(x))))
  cat("\nExplicit public selection after collapse:\n")
  print(collect(select(collapse(x), all_of(colnames(x)))))
  cat("\nPublic lazy query and raw direct CTE query schemas:\n")
  cte <- dbplyr::sql_options(cte = TRUE)
  ordinary_public <- attr(x, "marginplyr_public_query")
  print(names(DBI::dbGetQuery(con, dbplyr::sql_render(ordinary_public, sql_options = cte))))
  print(names(DBI::dbGetQuery(con, dbplyr::sql_render(x, sql_options = cte))))
  cat("\nSorted companion raw CTE SQL:\n")
  cat(as.character(dbplyr::sql_render(x, sql_options = cte)), "\n")
})
