pkgload::load_all(quiet = TRUE)
suppressPackageStartupMessages(library(dplyr))
key <- as.Date('2026-10-30')
dim(key) <- c(1L,1L)
input <- tibble(key=key, rid=1L)
expected <- union_all(mutate(input,sid=1L),mutate(input,key=vctrs::vec_init(key,1L),sid=2L))
expected <- relocate(expected,sid,.after=key)
stopifnot(identical(dim(expected$key),c(2L,1L)), identical(unclass(expected$key)[1L],20756))
actual <- tryCatch(expand_with_margins(input,.grouping=rollup(key),.margin_label=NULL,.id='sid'),error=identity)
cat('ordinary rows:',nrow(expected),'shape:',paste(dim(expected$key),collapse='x'),'class:',paste(class(expected$key),collapse=','),'\n')
cat('actual:',if(inherits(actual,'error')) paste(class(actual)[1L],conditionMessage(actual)) else 'returned','\n')
if('--assert' %in% commandArgs(TRUE)) stopifnot(identical(actual,expected))
