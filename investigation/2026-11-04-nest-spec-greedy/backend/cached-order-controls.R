Sys.setenv(TESTTHAT_PARALLEL = "false")
pkgload::load_all(Sys.getenv("MARGINPLYR_HUNT_SOURCE", getwd()), quiet = TRUE)
suppressPackageStartupMessages(library(dplyr))
input <- tibble(g = c("b", "a", NA, "a"), h = c("u", "v", "u", "v"), row = 1:4)
root <- dtplyr::lazy_dt(input)
y <- compute(root)
z <- compute(inner_join(y, rename(y, row2 = row), by = c("g", "h")))
q <- union_all(z, arrange(z, desc(row2)))
native <- collect(q)
print(native)
print(show_query(q))
result <- nest_with_margins(q, .grouping = rollup(g, h), .keep = TRUE, .id = "set", .sort = "last")
print(show_query(result))
actual <- as_tibble(result)
expected <- nest_with_margins(native, .grouping = rollup(g, h), .keep = TRUE, .id = "set", .sort = "last")
print(actual)
print(expected)
for (i in seq_len(nrow(expected))) {
  cat("cell", i, "\n")
  print(expected$data[[i]])
  print(actual$data[[i]])
  l <- arrange(as_tibble(expected$data[[i]]), row, row2)
  r <- arrange(as_tibble(actual$data[[i]]), row, row2)
  stopifnot(identical(l, r))
}
stopifnot(identical(collect(q), native))
cat("All cell multisets and native q before/after matched.\n")
