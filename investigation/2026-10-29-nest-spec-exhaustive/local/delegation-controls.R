args <- commandArgs(TRUE)
pkgload::load_all(if(length(args))args[[1L]]else ".",quiet=TRUE)
x<-tibble::tibble(time=as.POSIXlt(as.POSIXct(c(0,1,NA_real_),origin="1970-01-01",tz="America/New_York")),row_id=1:3)
ordinary<-dplyr::union_all(x,x)
nested<-nest_with_margins(x,.grouping=grouping_sets(grouping_set(time),grouping_set()),.margin_label=NULL,.keep=TRUE,.id="set")
cat("source time:",paste(class(x$time),collapse=","),"\n")
cat("ordinary union time:",paste(class(ordinary$time),collapse=","),"\n")
cat("nested kept time:",paste(class(nested$data[[1L]]$time),collapse=","),"\n")
stopifnot(inherits(ordinary$time,"POSIXct"),all(vapply(nested$data,function(z)identical(as.numeric(z$time),as.numeric(x$time[z$row_id])),logical(1))))
raw_input<-tibble::tibble(a=as.raw(c(1,2)),row_id=1:2)
raw_one<-nest_with_margins(raw_input,.grouping=grouping_set(a),.margin_label=NULL)
raw_rollup<-tryCatch(nest_with_margins(raw_input,.grouping=rollup(a),.margin_label=NULL),error=identity)
stopifnot(nrow(raw_one)==2L,inherits(raw_rollup,"marginplyr_error"),grepl("typed-missing",conditionMessage(raw_rollup),fixed=TRUE))
cat("PASS: POSIXlt differences followed ordinary union and raw typed-missing rejection required an omitted dimension\n")
