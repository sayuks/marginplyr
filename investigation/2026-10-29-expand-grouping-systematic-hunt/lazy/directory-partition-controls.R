suppressPackageStartupMessages({library(dplyr);library(arrow);pkgload::load_all(quiet=TRUE)})
root<-tempfile();dir.create(file.path(root,'7'),recursive=TRUE)
write_parquet(tibble(g=9L),file.path(root,'7','data.parquet'))
part<-DirectoryPartitioning$create(schema(sid=int32()))
input<-open_dataset(root,partitioning=part,schema=schema(g=int32()))
full<-open_dataset(root,partitioning=part)
local<-collect(input)
expected<-expand_with_margins(local,.grouping=rollup(g),.margin_label=NULL,.id='sid')
raw<-union_all(mutate(input,sid=1L),mutate(input,g=NA_integer_,sid=2L)) |> collect()
cat('ORDINARY_UNION\n');print(raw)
raw<-arrange(raw,sid)
stopifnot(identical(raw$sid,1:2),identical(raw$g,c(9L,NA_integer_)))
shapes<-list(projected=select(full,g),table=as_arrow_table(input),materialized=compute(input))
for(nm in names(shapes)) {
 shape<-shapes[[nm]]
 cat(nm,'\n')
 got<-expand_with_margins(shape,.grouping=rollup(g),.margin_label=NULL,.id='sid')|>collect()
 stopifnot(identical(arrange(got,sid),arrange(expected,sid)))
}
hive_root<-tempfile();dir.create(file.path(hive_root,'sid=7'),recursive=TRUE)
write_parquet(tibble(g=9L),file.path(hive_root,'sid=7','data.parquet'))
hive<-open_dataset(hive_root,partitioning=hive_partition(sid=int32()),schema=schema(g=int32()))
hive_result<-expand_with_margins(hive,.grouping=rollup(g),.margin_label=NULL,.id='sid')|>collect()
stopifnot(identical(arrange(hive_result,sid),arrange(expected,sid)))
cat('FULL_SCHEMA_PROJECTED, TABLE, COMPUTED, HIVE_NARROW controls passed\n')
unlink(c(root,hive_root),recursive=TRUE)
