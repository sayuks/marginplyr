suppressPackageStartupMessages({library(dplyr);library(arrow);pkgload::load_all(quiet=TRUE)})
root <- tempfile('directory-partition-')
dir.create(file.path(root,'7'),recursive=TRUE)
write_parquet(tibble(g=9L),file.path(root,'7','data.parquet'))
partitioning <- DirectoryPartitioning$create(schema(sid=int32()))
input <- open_dataset(root,partitioning=partitioning,schema=schema(g=int32()))
actual <- expand_with_margins(input,.grouping=rollup(g),.margin_label=NULL,.id='sid') |> collect()
expected <- expand_with_margins(collect(input),.grouping=rollup(g),.margin_label=NULL,.id='sid')
stopifnot(identical(collect(input)$g,9L), identical(expected$sid,1:2))
print(actual);print(expected)
correct <- identical(arrange(actual,sid),arrange(expected,sid))
cat('DIRECTORY_PARTITION_IDENTIFIER_CORRECT:',correct,'\n')
if('--assert' %in% commandArgs(TRUE)) stopifnot(correct)
unlink(root,recursive=TRUE)
