args <- commandArgs(TRUE)
pkgload::load_all(args[[1L]], quiet = TRUE)
suppressPackageStartupMessages(library(dplyr))
con <- DBI::dbConnect(RSQLite::SQLite(), ":memory:")
tryCatch({
  input <- data.frame(k = c("z", "a", NA), value = c(17L, 21L, 35L))
  names(input)[[2L]] <- "FaLsE"
  DBI::dbWriteTable(con, "observations", input)
  root <- tbl(con, "observations")
  source <- mutate(root, rank = row_number(k))
  expected <- collect(source)
  cat("Ordinary source collected.\n")
  equivalent <- function(x, y) {
    identical(names(x), names(y)) && identical(lapply(x, identity), lapply(y, identity))
  }
  stopifnot(equivalent(collect(select(source, everything())), expected))
  stopifnot(equivalent(collect(mutate(source)), expected))
  stopifnot(equivalent(collect(expand_with_margins(root)), collect(root)))
  cat("Projection/no-op/root controls passed.\n")
  safe <- rename(source, payload = all_of("FaLsE"))
  stopifnot(equivalent(collect(expand_with_margins(safe)), collect(safe)))
  cat("Safe-name control passed.\n")
  DBI::dbWriteTable(con, "frozen_source", expected)
  materialized <- tbl(con, "frozen_source")
  stopifnot(equivalent(collect(expand_with_margins(materialized)), collect(materialized)))
  cat("Source/projection/no-op mutation/root/safe-name/materialized controls passed.\n")
  print(expected)
  actual <- tryCatch(collect(expand_with_margins(source)), error = identity)
  ok <- !inherits(actual, "error") && equivalent(actual, expected)
  cat("Identity expansion contract:", if (ok) "PASS" else "FAIL", "\n")
  if (inherits(actual, "error")) cat(class(actual)[[1L]], conditionMessage(actual), "\n") else print(actual)
  if ("--assert" %in% args) stopifnot(ok)
}, finally = DBI::dbDisconnect(con))
print(sessionInfo())
