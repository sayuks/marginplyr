library(DBI)
con <- dbConnect(RSQLite::SQLite(), ':memory:')
other <- dbConnect(RSQLite::SQLite(), ':memory:')
events <- character()
mark <- function(x) events <<- c(events, x)
report <- function(label) { cat(label, ': ', paste(events, collapse=' | '), '\n', sep=''); events <<- character() }
saved_generic <- DBI::dbSendQuery
saved_method <- selectMethod('dbSendQuery', c('SQLiteConnection','character'))
trace('dbSendQuery', where=asNamespace('DBI'), tracer=quote(.GlobalEnv$mark(paste('generic',statement))), exit=quote(.GlobalEnv$mark('generic-exit')), print=FALSE)
dbGetQuery(con, 'SELECT 1 AS a')
report('dbGetQuery via namespace import')
r <- saved_generic(con, 'SELECT 2 AS a'); dbClearResult(r)
report('generic saved before trace')
untrace('dbSendQuery', where=asNamespace('DBI'))
trace('dbSendQuery', signature=c('SQLiteConnection','character'), where=asNamespace('RSQLite'), tracer=quote(.GlobalEnv$mark(paste('method',statement))), exit=quote(.GlobalEnv$mark('method-exit')), print=FALSE)
dbGetQuery(con, 'SELECT 3 AS a')
report('method normal return')
tryCatch(dbGetQuery(con, 'NOT_SQL'), error=function(e) mark(paste('caught',conditionMessage(e))))
report('method error')
r <- saved_generic(con, 'SELECT 4 AS a'); dbClearResult(r)
report('saved generic through current method')
r <- saved_method(con, 'SELECT 5 AS a'); dbClearResult(r)
report('method saved before trace')
untrace('dbSendQuery', signature=c('SQLiteConnection','character'), where=asNamespace('RSQLite'))
trace('dbSendQuery', signature=c('SQLiteConnection','character'), where=asNamespace('RSQLite'), tracer=quote({ if (identical(conn, .GlobalEnv$con)) stop('recording unavailable') }), print=FALSE)
tryCatch(dbExecute(con, 'CREATE TABLE blocked (a INTEGER)'), error=function(e) mark(conditionMessage(e)))
dbGetQuery(other, 'SELECT 6 AS a')
report('selected connection rejection, other connection normal')
untrace('dbSendQuery', signature=c('SQLiteConnection','character'), where=asNamespace('RSQLite'))
cat('blocked table exists:', dbExistsTable(con,'blocked'), '\n')
dbDisconnect(con); dbDisconnect(other)
