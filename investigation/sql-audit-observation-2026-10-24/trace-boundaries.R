events <- character()
mark <- function(x) events <<- c(events, x)
report <- function(label) { cat(label, ': ', paste(events, collapse = ' | '), '\n', sep = ''); events <<- character() }
f <- function() { mark('body'); 1 }
trace('f', tracer = quote({ mark('entry'); stop('recording unavailable') }), print = FALSE)
tryCatch(f(), error = function(e) mark(conditionMessage(e)))
report('entry rejection')
old <- tracingState(FALSE)
f()
tracingState(old)
report('global tracing disabled')
untrace('f')
f <- function(fail = FALSE) { if (fail) stop('original failure'); NULL }
trace('f', exit = quote(mark(paste0('exit:', if (identical(returnValue('NO_RETURN'), 'NO_RETURN')) 'no-return' else 'returned-null'))), print = FALSE)
f(FALSE)
tryCatch(f(TRUE), error = function(e) mark(paste0('outer-error:', conditionMessage(e))))
report('exit and error')
untrace('f')
f <- function() { on.exit(mark('own-cleanup')); 1 }
trace('f', exit = quote(mark('trace-exit')), print = FALSE)
f()
report('overwritten exit')
untrace('f')
f <- function() 1
trace('f', tracer = quote(mark('existing')), print = FALSE)
saved <- f
trace('f', tracer = quote(mark('audit')), print = FALSE)
f()
untrace('f')
f()
report('replace then untrace')
f <- saved
f()
report('restore saved ordinary binding')
untrace('f')
setClass('AuditProbeClass', slots = c(value = 'numeric'))
setGeneric('auditProbe', function(x) standardGeneric('auditProbe'))
setMethod('auditProbe', 'AuditProbeClass', function(x) 1)
trace('auditProbe', signature = 'AuditProbeClass', tracer = quote(mark('existing-method')), print = FALSE)
saved_method <- selectMethod('auditProbe', 'AuditProbeClass')
trace('auditProbe', signature = 'AuditProbeClass', tracer = quote(mark('audit-method')), print = FALSE)
auditProbe(new('AuditProbeClass'))
untrace('auditProbe', signature = 'AuditProbeClass')
auditProbe(new('AuditProbeClass'))
report('method replace then untrace')
setMethod('auditProbe', 'AuditProbeClass', saved_method)
auditProbe(new('AuditProbeClass'))
report('restore saved method definition')
