pkgload::load_all('.', quiet=TRUE)
suppressPackageStartupMessages(library(dplyr))
co<-DBI::dbConnect(duckdb::duckdb(shared_home=FALSE))
d<-setNames(tibble(k=c('a','b'),v=c(1L,3L)),c('..0','v'))
s<-copy_to(co,d,'dd')
report<-function(label,code){cat('\n',label,'\n');tryCatch(print(force(code)),error=function(e){cat(class(e),'\n',conditionMessage(e),'\n');print(conditionCall(e))})}
report('source',collect(s))
report('ordinary .by',collect(summarise(s,n=n(),.by=all_of('..0'))))
report('ordinary group_by',collect(summarise(group_by(s,pick(all_of('..0'))),n=n(),.groups='drop')))
report('fixed one set',collect(summarize_with_margins(s,n=n(),.by=all_of('..0'),.margin_label=NULL)))
report('dimension one set',collect(summarize_with_margins(s,n=n(),.grouping=grouping_set(all_of('..0')),.margin_label=NULL)))
report('native rollup',collect(summarize_with_margins(s,n=n(),.grouping=rollup(all_of('..0')),.margin_label=NULL)))
report('portable rollup',collect(summarize_with_margins(s,n=n(),.grouping=rollup(all_of('..0')),.margin_label=NULL,.id='sid',.duplicates='keep')))
DBI::dbDisconnect(co)
