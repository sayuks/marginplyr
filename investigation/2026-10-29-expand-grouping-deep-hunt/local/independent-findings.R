pkgload::load_all('.',quiet=TRUE)
suppressPackageStartupMessages(library(dplyr))
q <- dtplyr::lazy_dt(tibble(g=11:12,v=1:2))
x <- mutate(q,g=v,g=factor(g))
actual <- collect(expand_with_margins(x,.grouping=rollup(g),.id='sid'))
expected <- expand_with_margins(collect(x),.grouping=rollup(g),.id='sid')
stopifnot(all(is.na(actual$g[actual$sid==1L])),identical(as.character(expected$g[expected$sid==1L]),c('1','2')))
cat('DTPLYR detail actual:',as.character(actual$g[actual$sid==1L]),' expected:',as.character(expected$g[expected$sid==1L]),'\n')
con <- DBI::dbConnect(duckdb::duckdb(shared_home=FALSE))
source <- copy_to(con,tibble(g=c('a','b'),v=1:2,.env=c('x','y')),'independent_source')
z <- expand_with_margins(source,.grouping=rollup(g),.margin_label=NULL)
y <- compute(group_by(z,g),analyze=FALSE)
summary <- collect(summarise(y,total=sum(v,na.rm=TRUE)))
stopifnot(identical(group_vars(y),character()),nrow(summary)==1L,summary$total==6)
cat('DUCKDB groups after compute:',length(group_vars(y)),' summary:',summary$total,'\n')
ordinary <- compute(group_by(select(source,g,v),g),analyze=FALSE)
stopifnot(identical(group_vars(ordinary),'g'))
for (kind in c('ordinary','margin')) {
  DBI::dbWriteTable(con,'independent_dest',data.frame(sentinel=777L),overwrite=TRUE,temporary=TRUE)
  er <- tryCatch(compute(if(kind=='margin')z else select(source,g,v),name='independent_dest',overwrite=TRUE,indexes=list('absent'),analyze=FALSE),error=identity)
  saved <- DBI::dbReadTable(con,'independent_dest')
  stopifnot(inherits(er,'error'))
  if(kind=='ordinary') stopifnot(identical(saved,data.frame(sentinel=777L))) else stopifnot(!'sentinel'%in%names(saved),nrow(saved)==4L)
  cat('DUCKDB invalid index',kind,'destination columns:',paste(names(saved),collapse=','),'\n')
}
DBI::dbDisconnect(con,shutdown=TRUE)
