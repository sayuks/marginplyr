Sys.setenv(TESTTHAT_PARALLEL = "false")
pkgload::load_all(quiet = TRUE)
root <- new.env(parent = globalenv())
root$source <- data.frame(g = c("a", "b"), x = c(1, 3))
input <- evalq(dtplyr::lazy_dt(source), root)
plain <- summarize_with_margins(input, value = sum(x), .grouping = rollup(g))
query <- summarize_with_margins(input, value = sum(x), fraction = share_of_total(value), .grouping = rollup(g))
expected <- as.data.frame(dplyr::collect(query))
stopifnot(identical(expected$fraction, c(.25, .75, 1)))
root$is.na <- function(x) rep(TRUE, length(x))
observed <- as.data.frame(dplyr::collect(query))
stopifnot(identical(dplyr::collect(input)$x, c(1,3)), identical(dplyr::collect(plain)$value, c(1,3,4)))
print(expected)
print(observed)
cat("Source and no-share controls: passed\n")
if ("--assert" %in% commandArgs(TRUE)) stopifnot(identical(observed$fraction, expected$fraction))
stopifnot(identical(observed$fraction, c(NA_real_, NA_real_, 1)))
rm("is.na", envir = root)
stopifnot(identical(as.data.frame(dplyr::collect(query))$fraction, expected$fraction))
cat("Binding removal restored correct ratios\n")
