args <- commandArgs(trailingOnly = TRUE)
repo <- if (length(args)) normalizePath(args[[1L]]) else getwd()
suppressPackageStartupMessages(library(dplyr))
devtools::load_all(repo, quiet = TRUE)
d <- tibble(x=1:2)
cap <- function(expr) tryCatch(expr,error=identity)
expected <- cap(summarise(d,z=nrow(pick())))
actual <- cap(summarize_with_margins(d,z=nrow(pick())))
cat('dplyr error:',conditionMessage(expected),'\n')
cat('margin actual:\n');print(actual)
cat('explicit everything control:',identical(summarise(d,z=nrow(pick(everything()))),summarize_with_margins(d,z=nrow(pick(everything())))),'\n')
cat('explicit empty selection control:',identical(summarise(d,z=nrow(pick(c()))),summarize_with_margins(d,z=nrow(pick(c())))),'\n')
cat('parenthesized dplyr:',inherits(cap(summarise(d,z=nrow((pick)()))),'error'),'margin:',inherits(cap(summarize_with_margins(d,z=nrow((pick)()))),'error'),'\n')
cat('dtplyr dplyr:',inherits(cap(collect(summarise(dtplyr::lazy_dt(d),z=nrow(pick())))),'error'),'margin:');print(cap(collect(summarize_with_margins(dtplyr::lazy_dt(d),z=nrow(pick())))))
stopifnot(inherits(expected, 'error'), grepl('Must supply at least one input', conditionMessage(expected), fixed = TRUE))
stopifnot(identical(summarise(d,z=nrow(pick(everything()))),summarize_with_margins(d,z=nrow(pick(everything())))))
stopifnot(identical(summarise(d,z=nrow(pick(c()))),summarize_with_margins(d,z=nrow(pick(c())))))
if(!inherits(actual,'error') || !grepl('Must supply at least one input', conditionMessage(actual), fixed=TRUE)) stop('BUG: empty pick() lost dplyr mandatory-input refusal',call.=FALSE)
