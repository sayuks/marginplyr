args <- commandArgs(TRUE)
stopifnot(length(args) == 2L)
Sys.setenv(TESTTHAT_PARALLEL = "false")
pkgload::load_all(args[[1L]], quiet = TRUE)
library(dplyr)
rows <- list()
for (type in c("right", "interval", "mstate")) for (n in c(1L, 7L)) for (depth in 0:2) {
  time <- rep(c(2, NA, 1, 0, 9, 7, NA), length.out = n)
  status <- rep(c(1, NA, 0, 1, 0, 1, NA), length.out = n)
  g <- if (type == "right") survival::Surv(time, status) else if (type == "interval") survival::Surv(time, time + 1, rep(c(3, NA, 0, 1, 2, 1, NA), length.out = n), type = "interval") else survival::Surv(time, factor(status, levels = 0:1))
  for (i in seq_len(depth)) g <- tibble(inner = g)
  x <- tibble(g = g, rid = seq_len(n))
  ordinary <- tryCatch(arrange(x, g), error = identity)
  expansion <- tryCatch(expand_with_margins(x, .grouping = rollup(g), .margin_label = NULL, .sort = "last"), error = identity)
  unsorted <- tryCatch(expand_with_margins(x, .grouping = rollup(g), .margin_label = NULL), error = identity)
  rows[[length(rows) + 1L]] <- data.frame(type, n, depth, ordinary_error = inherits(ordinary, "error"), expansion_error = inherits(expansion, "error"), unsorted_rows = nrow(unsorted), ordinary_message = if (inherits(ordinary, "error")) conditionMessage(ordinary) else "", expansion_message = if (inherits(expansion, "error")) conditionMessage(expansion) else "")
}
result <- bind_rows(rows)
write.csv(result, args[[2L]], row.names = FALSE)
print(result[, 1:6])
stopifnot(all(result$ordinary_error), all(result$expansion_error), all(result$unsorted_rows == 2L * result$n))
